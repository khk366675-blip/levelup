export function getRegionalTheme(regionId: string): RegionalThemeData {
  // regionId가 seoul, incheon, busan, jeju 이면 해당 테마 리턴
  if (REGIONAL_THEMES[regionId]) {
    return REGIONAL_THEMES[regionId];
  }
  // 한국의 default fallback은 seoul로
  if (regionId === 'kr') {
    return REGIONAL_THEMES['seoul'];
  }
  // 그 외 15개국 코드 (us, uk, ru, cn, jp, de 등)가 사전에 있으면 리턴
  if (REGIONAL_THEMES[regionId]) {
    return REGIONAL_THEMES[regionId];
  }
  // 없으면 default
  return REGIONAL_THEMES['default'];
}
