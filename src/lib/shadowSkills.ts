const isNamedShadow = (shadow: OwnedShadow): boolean =>
  Boolean(shadow.isNamed || shadow.isGateNamed || shadow.isAchievementNamed)

const getQualityCap = (shadow: OwnedShadow): ShadowSkillQuality => {
  if (isNamedShadow(shadow)) return 'unique'
  if (shadow.rarity === 'legendary') return 'legendary'
  if (shadow.rarity === 'epic') return 'elite'
  if (shadow.rarity === 'rare' || shadow.rarity === 'uncommon') return 'refined'
  if ((shadow.evolutionStage ?? 0) > 0 || shadow.innateGrade === 'S') return 'refined'
  return 'basic'
}

const getSlotCounts = (shadow: OwnedShadow, definition?: ShadowDefinition): { active: number; passive: number } => {
  const evolution = shadow.evolutionStage ?? 0
  const hasDefinitionPassive = Boolean(definition?.shadowPassiveIds?.length || definition?.shadowUniquePassiveIds?.length)
  if (isNamedShadow(shadow) || shadow.rarity === 'legendary') {
    return { active: Math.min(2, 1 + (evolution >= 3 ? 1 : 0) + (isNamedShadow(shadow) ? 1 : 0)), passive: 2 }
  }
  if (shadow.rarity === 'epic') return { active: 1 + (evolution >= 3 ? 1 : 0), passive: 1 + (evolution >= 2 ? 1 : 0) }
  if (shadow.rarity === 'rare' || shadow.rarity === 'uncommon') return { active: 1, passive: 1 }
  return { active: 1, passive: (hasDefinitionPassive || shadow.innateGrade === 'A' || shadow.innateGrade === 'S' || evolution > 0) ? 1 : 0 }
}

const qualityAllowed = (quality: ShadowSkillQuality, cap: ShadowSkillQuality): boolean =>
  QUALITY_RANK[quality] <= QUALITY_RANK[cap]

const getAbilityPriority = (ability: { source?: ShadowAbilitySource; qualityTier: ShadowSkillQuality }): number => {
  if (ability.source === 'unique') return 100 + QUALITY_RANK[ability.qualityTier]
  if (ability.source === 'prototype') return 50 + QUALITY_RANK[ability.qualityTier]
  if (ability.source === 'template') return 25 + QUALITY_RANK[ability.qualityTier]
  return QUALITY_RANK[ability.qualityTier]
}

const byDefinitionAwareAbilityPriorityDesc = <T extends { qualityTier: ShadowSkillQuality; id: string; source?: ShadowAbilitySource }>(
  definitionIds: Set<string>,
) => (a: T, b: T): number => {
  const aDefinitionBonus = definitionIds.has(a.id) ? 10 : 0
  const bDefinitionBonus = definitionIds.has(b.id) ? 10 : 0
  return (getAbilityPriority(b) + bDefinitionBonus) - (getAbilityPriority(a) + aDefinitionBonus) || a.id.localeCompare(b.id)
}

const uniqueById = <T extends { id: string }>(items: T[]): T[] => {
  const seen = new Set<string>()
  return items.filter(item => {
    if (seen.has(item.id)) return false
    seen.add(item.id)
    return true
  })
}

const getDefinitionSkills = (definition?: ShadowDefinition): ShadowSkillDefinition[] => {
  const ids = [...(definition?.shadowUniqueSkillIds ?? []), ...(definition?.shadowSkillIds ?? [])]
  if (!ids.length) return []
  return ids
    .map(id => ALL_SHADOW_SKILLS.find(skill => skill.id === id))
    .filter((skill): skill is ShadowSkillDefinition => Boolean(skill))
}

const getDefinitionPassives = (definition?: ShadowDefinition): ShadowPassiveDefinition[] => {
  const ids = [...(definition?.shadowUniquePassiveIds ?? []), ...(definition?.shadowPassiveIds ?? [])]
  if (!ids.length) return []
  return ids
    .map(id => ALL_SHADOW_PASSIVES.find(passive => passive.id === id))
    .filter((passive): passive is ShadowPassiveDefinition => Boolean(passive))
}

export const getShadowSkillCandidates = (shadow: OwnedShadow, definition?: ShadowDefinition): ShadowSkillDefinition[] => {
  const qualityCap = getQualityCap(shadow)
  const base = ROLE_SKILLS[shadow.role].filter(skill => qualityAllowed(skill.qualityTier, qualityCap))
  const special = isNamedShadow(shadow) ? [NAMED_GENERIC_SKILL] : []
  const definitionSkills = getDefinitionSkills(definition).filter(skill => qualityAllowed(skill.qualityTier, qualityCap))
  const definitionIds = new Set(definitionSkills.map(skill => skill.id))
  return uniqueById([...definitionSkills, ...special, ...base]).sort(byDefinitionAwareAbilityPriorityDesc(definitionIds))
}

export const getShadowPassiveCandidates = (shadow: OwnedShadow, definition?: ShadowDefinition): ShadowPassiveDefinition[] => {
  const qualityCap = getQualityCap(shadow)
  const base = ROLE_PASSIVES[shadow.role].filter(passive => qualityAllowed(passive.qualityTier, qualityCap))
  const special = isNamedShadow(shadow) ? [NAMED_GENERIC_PASSIVE] : []
  const definitionPassives = getDefinitionPassives(definition).filter(passive => qualityAllowed(passive.qualityTier, qualityCap))
  const definitionIds = new Set(definitionPassives.map(passive => passive.id))
  return uniqueById([...definitionPassives, ...special, ...base]).sort(byDefinitionAwareAbilityPriorityDesc(definitionIds))
}

const getShadowBehaviorProfile = (shadow: OwnedShadow): ShadowCombatBehaviorProfile => ({
  preferredActions: PREFERRED_ACTIONS[shadow.role],
  actionPriorityWeights: ACTION_WEIGHTS[shadow.role],
  maxActionsPerRound: isNamedShadow(shadow) || shadow.rarity === 'legendary' ? 2 : 1,
  duplicateRolePenalty: shadow.rarity === 'legendary' ? 0.82 : 0.75,
  bossPriorityBonus: shadow.role === 'analyst' ? 0.16 : shadow.role === 'assault' || shadow.role === 'guard' ? 0.1 : 0.06,
})

const getShadowExpeditionBehaviorProfile = (shadow: OwnedShadow): ShadowExpeditionBehaviorProfile => {
  const commandMap: Record<ShadowRole, ShadowExpeditionBehaviorProfile['preferredCommands']> = {
    assault: ['attack', 'analyze', 'defend'],
    guard: ['defend', 'support', 'attack'],
    hunter: ['attack', 'scout', 'analyze'],
    scout: ['scout', 'analyze', 'support'],
    support: ['support', 'defend', 'scout'],
    analyst: ['analyze', 'scout', 'support'],
  }
  return {
    preferredCommands: commandMap[shadow.role],
    riskControlWeight: shadow.role === 'guard' || shadow.role === 'support' ? 1 : shadow.role === 'analyst' ? 0.9 : 0.65,
    phaseTempoWeight: shadow.role === 'scout' || shadow.role === 'hunter' ? 1 : 0.7,
    rewardSenseWeight: shadow.role === 'hunter' || shadow.role === 'scout' ? 0.9 : 0.62,
  }
}

const getShadowActionProfile = (
  shadow: OwnedShadow,
  activeSkills: ShadowSkillDefinition[],
  passives: ShadowPassiveDefinition[],
  definition?: ShadowDefinition,
): ShadowActionProfile => {
  const primarySkill = activeSkills[0]
  const primaryPassive = passives[0]
  const apex = isNamedShadow(shadow) || shadow.rarity === 'legendary' || shadow.innateGrade === 'S'
  return {
    boardLane: BOARD_LANE[shadow.role],
    spriteScaleHint: shadow.rarity === 'legendary' ? 1.12 : shadow.rarity === 'epic' ? 1.06 : 1,
    auraIntensitySource: apex ? 'combatPower' : shadow.innateGrade === 'A' ? 'innateGrade' : 'rarity',
    actionCue: definition?.shadowUniqueActionCue ?? primarySkill?.actionCue ?? PREFERRED_ACTIONS[shadow.role][0],
    effectColor: primarySkill?.effectColor ?? ROLE_EFFECT_COLOR[shadow.role],
    impactTiming: primarySkill?.impactTiming ?? (apex ? 'heavy' : 'normal'),
    animationHooks: {
      idle: `${shadow.role}-idle`,
      activeSkill: primarySkill?.animationCue,
      passiveTrigger: primaryPassive?.triggerCue,
      guard: shadow.role === 'guard' ? 'guard-stance' : undefined,
      finisher: shadow.role === 'assault' || shadow.role === 'hunter' ? 'finisher-cue' : undefined,
    },
  }
}

export const formatShadowTriggerSummary = (trigger?: ShadowTriggerCondition): string =>
  trigger?.summary ?? 'Always available candidate'

export const formatShadowSkillSummary = (skill: ShadowSkillDefinition): string =>
  `${skill.shortLabel} · ${skill.qualityTier.toUpperCase()} · ${formatShadowTriggerSummary(skill.trigger)}`

export const formatShadowPassiveSummary = (passive: ShadowPassiveDefinition): string =>
  `${passive.shortLabel} · ${passive.qualityTier.toUpperCase()} · ${formatShadowTriggerSummary(passive.condition)}`

export const getShadowAbilitySourceLabel = (ability: { source?: ShadowAbilitySource; qualityTier: ShadowSkillQuality }): string => {
  if (ability.source === 'unique' || ability.qualityTier === 'unique') return 'UNIQUE'
  if (ability.source === 'prototype') return 'PROTOTYPE'
  if (ability.source === 'template') return 'TEMPLATE'
  return 'GENERIC'
}

export const getShadowCombatUnitProfile = (
  shadow: OwnedShadow,
  definition: ShadowDefinition | undefined = getShadowDefinition(shadow.definitionId),
): ShadowCombatUnitProfile => {
  const combatProfile = getShadowCombatProfile(shadow, definition)
  const qualityCap = getQualityCap(shadow)
  const slots = getSlotCounts(shadow, definition)
  const activeSkills = getShadowSkillCandidates(shadow, definition).slice(0, slots.active)
  const passives = getShadowPassiveCandidates(shadow, definition).slice(0, slots.passive)

  return {
    shadowId: shadow.instanceId,
    definitionId: shadow.definitionId,
    displayState: 'revealed',
    role: shadow.role,
    rarity: shadow.rarity,
    innateGrade: shadow.innateGrade ?? 'B',
    level: shadow.level ?? 1,
    enhancement: shadow.enhancementLevel ?? 0,
    evolutionStage: shadow.evolutionStage ?? 0,
    stats: combatProfile.stats,
    combatPower: combatProfile,
    activeSkills,
    passives,
    behavior: getShadowBehaviorProfile(shadow),
    expeditionBehavior: getShadowExpeditionBehaviorProfile(shadow),
    actionProfile: getShadowActionProfile(shadow, activeSkills, passives, definition),
    gradeTuning: GRADE_TUNING[shadow.innateGrade ?? 'B'],
    qualityCap,
    summaryBadges: [
      combatProfile.roleTag,
      activeSkills[0]?.shortLabel,
      passives[0]?.shortLabel,
    ].filter((badge): badge is string => Boolean(badge)),
  }
}

export const getShadowCombatUnitProfiles = (shadows: OwnedShadow[]): ShadowCombatUnitProfile[] =>
  shadows.map(shadow => getShadowCombatUnitProfile(shadow))
