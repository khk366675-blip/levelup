export type ShadowSkillQuality = 'basic' | 'refined' | 'elite' | 'legendary' | 'unique'
export type ShadowSkillTiming =
  | 'battle_start'
  | 'round_start'
  | 'after_hunter_action'
  | 'before_enemy_action'
  | 'after_enemy_action'
  | 'finisher_window'
  | 'wave_start'
export type ShadowSkillTarget = 'enemy' | 'boss' | 'hunter' | 'party' | 'self'
export type ShadowEffectKind = 'damage' | 'guard' | 'control' | 'support' | 'bossing' | 'hybrid'
export type ShadowAbilitySource = 'generic' | 'template' | 'prototype' | 'unique'
export type ShadowPassiveEffectKind =
  | 'stat_shift'
  | 'trigger_boost'
  | 'cooldown'
  | 'survival'
  | 'synergy'
  | 'bossing'
export type ShadowStackRule = 'none' | 'unique' | 'diminishing' | 'role_capped'
export type ShadowActionKind = 'attack' | 'guard' | 'control' | 'support' | 'finisher' | 'bossing'
export type ShadowBoardLane = 'front' | 'flank' | 'rear' | 'anchor'
export type ShadowAuraIntensitySource = 'rarity' | 'innateGrade' | 'combatPower'

export interface ShadowTriggerCondition {
  timing: ShadowSkillTiming | 'hp_threshold' | 'target_low_hp' | 'boss_present' | 'after_crit' | 'after_kill'
  hpThreshold?: number
  targetHpThreshold?: number
  requiresBoss?: boolean
  roleCombo?: ShadowRole[]
  cooldownGate?: number
  summary: string
}

export interface ShadowSkillDefinition {
  id: string
  name: string
  shortLabel: string
  description: string
  roleTags: ShadowRole[]
  qualityTier: ShadowSkillQuality
  timing: ShadowSkillTiming
  target: ShadowSkillTarget
  effectKind: ShadowEffectKind
  statScaling: Partial<Record<ShadowStatKey, number>>
  baseChance: number
  cooldownRounds: number
  cap?: number
  trigger?: ShadowTriggerCondition
  actionCue: string
  effectColor: string
  impactTiming: 'quick' | 'normal' | 'heavy' | 'apex'
  animationCue?: string
  source?: ShadowAbilitySource
}

export interface ShadowPassiveDefinition {
  id: string
  name: string
  shortLabel: string
  description: string
  roleTags: ShadowRole[]
  qualityTier: ShadowSkillQuality
  effectKind: ShadowPassiveEffectKind
  statScaling: Partial<Record<ShadowStatKey, number>>
  condition?: ShadowTriggerCondition
  stackRule: ShadowStackRule
  actionCue: string
  triggerCue?: string
  source?: ShadowAbilitySource
}

export interface ShadowCombatBehaviorProfile {
  preferredActions: ShadowActionKind[]
  actionPriorityWeights: Record<ShadowActionKind, number>
  maxActionsPerRound: number
  duplicateRolePenalty: number
  bossPriorityBonus: number
}

export interface ShadowExpeditionBehaviorProfile {
  preferredCommands: Array<'attack' | 'defend' | 'scout' | 'support' | 'analyze'>
  riskControlWeight: number
  phaseTempoWeight: number
  rewardSenseWeight: number
}

export interface ShadowActionProfile {
  boardLane: ShadowBoardLane
  spriteScaleHint: number
  auraIntensitySource: ShadowAuraIntensitySource
  actionCue: string
  effectColor: string
  impactTiming: 'quick' | 'normal' | 'heavy' | 'apex'
  animationHooks: {
    idle: string
    activeSkill?: string
    passiveTrigger?: string
    guard?: string
    finisher?: string
  }
}

export interface ShadowGradeTuningProfile {
  procStability: number
  effectScaling: number
  cooldownStability: number
  growthScaling: number
}

export interface ShadowActionEvent {
  sourceShadowId: string
  skillId?: string
  passiveId?: string
  abilityName?: string
  sourceAbility?: ShadowAbilitySource
  timing: ShadowSkillTiming | string
  effectKind: ShadowEffectKind | ShadowPassiveEffectKind
  valuePreview: number
  targetType?: 'player' | 'monster' | 'self' | 'party'
  targetId?: string
  logCue: 'minor' | 'normal' | 'high' | 'apex'
  animationCue?: string
  actionCue?: string
  effectColor?: string
  impactTiming?: 'quick' | 'normal' | 'heavy' | 'apex'
  boardLane?: ShadowBoardLane
  runtimeCategory?: ShadowActionKind | 'tempo'
}

