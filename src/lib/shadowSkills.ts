export const formatShadowTriggerSummary = (trigger?: ShadowTriggerCondition): string => {
  const sum = trigger?.summary ?? 'Always available candidate'
  return SHADOW_TRIGGER_SUMMARIES[sum] || sum
}

export const formatShadowSkillSummary = (skill: ShadowSkillDefinition): string => {
  const shortLabelKo = getShadowSkillDisplayName(skill.shortLabel)
  const qualityTierKo = translateQualityTier(skill.qualityTier)
  const triggerKo = formatShadowTriggerSummary(skill.trigger)
  return `${shortLabelKo} · ${qualityTierKo} · ${triggerKo}`
}

export const formatShadowPassiveSummary = (passive: ShadowPassiveDefinition): string => {
  const shortLabelKo = getShadowSkillDisplayName(passive.shortLabel)
  const qualityTierKo = translateQualityTier(passive.qualityTier)
  const triggerKo = formatShadowTriggerSummary(passive.condition)
  return `${shortLabelKo} · ${qualityTierKo} · ${triggerKo}`
}

export const getShadowAbilitySourceLabel = (ability: { source?: ShadowAbilitySource; qualityTier: ShadowSkillQuality }): string => {
  if (ability.source === 'unique' || ability.qualityTier === 'unique') return '고유형'
  if (ability.source === 'prototype') return '실험형'
  if (ability.source === 'template') return '표준형'
  return '일반형'
}

export const getShadowCombatUnitProfile = (
  shadow: OwnedShadow,
  definition: ShadowDefinition | undefined = getShadowDefinition(shadow.definitionId),
): ShadowCombatUnitProfile => {
  const combatProfile = getShadowCombatProfile(shadow, definition)
  const qualityCap = getQualityCap(shadow)
  const slots = getSlotCounts(shadow, definition)
  const activeSkills = getShadowSkillCandidates(shadow, definition).slice(0, slots.active)
  const passives = getShadowPassiveCandidates(shadow, definition).slice(0, slots.passive)

  return {
    shadowId: shadow.instanceId,
    definitionId: shadow.definitionId,
    displayState: 'revealed',
    role: shadow.role,
    rarity: shadow.rarity,
    innateGrade: shadow.innateGrade ?? 'B',
    level: shadow.level ?? 1,
    enhancement: shadow.enhancementLevel ?? 0,
    evolutionStage: shadow.evolutionStage ?? 0,
    stats: combatProfile.stats,
    combatPower: combatProfile,
    activeSkills,
    passives,
    behavior: getShadowBehaviorProfile(shadow),
    expeditionBehavior: getShadowExpeditionBehaviorProfile(shadow),
    actionProfile: getShadowActionProfile(shadow, activeSkills, passives, definition),
    gradeTuning: GRADE_TUNING[shadow.innateGrade ?? 'B'],
    qualityCap,
    summaryBadges: [
      combatProfile.roleTag,
      activeSkills[0]?.shortLabel,
      passives[0]?.shortLabel,
    ].filter((badge): badge is string => Boolean(badge)),
  }
}

