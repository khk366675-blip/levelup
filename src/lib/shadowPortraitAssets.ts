// ---------------------------------------------------------------------------
// Helper functions (all safe with undefined input, never throw)
// ---------------------------------------------------------------------------

export function getShadowPortraitAsset(portraitKey: string | undefined): string | undefined {
  if (!portraitKey) return undefined
  return SHADOW_PORTRAIT_ASSETS[portraitKey]
}

export function hasShadowPortraitAsset(portraitKey: string | undefined): boolean {
  if (!portraitKey) return false
  return Object.prototype.hasOwnProperty.call(SHADOW_PORTRAIT_ASSETS, portraitKey)
}

export function getShadowPortraitAssetStatus(portraitKey: string | undefined): ShadowPortraitAssetStatus {
  if (!portraitKey) return 'missing'
  const entry = SHADOW_PORTRAIT_REGISTRY[portraitKey]
  if (!entry) return 'missing'
  return entry.status
}

